export function ensureHunterStyles() {
  const all = styles.all();
  for (const seed of [HUNTER_WX_WRITING, HUNTER_WX_COVER, HUNTER_WX_ILLUS]) {
    if (!all.some((s) => s.name === seed.name)) styles.create({ ...seed, inUse: true });
  }
}

